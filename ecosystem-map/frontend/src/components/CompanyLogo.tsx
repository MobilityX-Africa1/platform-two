function extractDomain(url: string | null | undefined): string | null {
  if (!url) return null;
  try {
    const { hostname } = new URL(url.startsWith('http') ? url : `https://${url}`);
    return hostname.replace(/^www\./, '');
  } catch {
    return null;
  }
}

interface CompanyLogoProps {
  name: string | null | undefined;
  website?: string | null;
  size?: number;
}

export function CompanyLogo({ name, website, size = 28 }: CompanyLogoProps) {
  const [failed, setFailed] = useState(false);
  const localSrc = name ? LOCAL_LOGO_OVERRIDES[name.trim().toLowerCase()] : undefined;
  const domain = extractDomain(website);
  const src = localSrc || (domain ? `https://www.google.com/s2/favicons?domain=${domain}&sz=128` : null);

  if (!src || failed) {
    return (
      <span
        style={{
          width: size,
          height: size,
          borderRadius: 6,
          background: 'var(--plum-bg)',
          color: 'var(--plum)',
          display: 'inline-flex',
          alignItems: 'center',
          justifyContent: 'center',
          fontFamily: 'var(--font-display)',
          fontWeight: 700,
          fontSize: size * 0.42,
          flexShrink: 0,
        }}
      >
        {name?.[0]?.toUpperCase() || '?'}
      </span>
    );
  }

  return (
    <img
      src={src}
      alt={`${name} logo`}
      width={size}
      height={size}
      style={{
        width: size,
        height: size,
        borderRadius: 6,
        objectFit: 'contain',
        background: 'var(--surface)',
        boxShadow: '0 0 0 1px var(--border)',
        flexShrink: 0,
      }}
      onError={() => setFailed(true)}
      loading="lazy"
    />
  );
}
